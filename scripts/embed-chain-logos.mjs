import { readFileSync, writeFileSync } from 'node:fs';

const assets = { btc: 'btc.svg', eth: 'eth.png', bnb: 'bnb.svg', tron: 'tron.png', base: 'base.svg', sol: 'sol.svg' };
const entries = Object.entries(assets).map(([chain, file]) => {
  const mime = file.endsWith('.svg') ? 'image/svg+xml' : 'image/png';
  const data = readFileSync(new URL(`../public/chain-logos/${file}`, import.meta.url)).toString('base64');
  return `  ${chain}: ${JSON.stringify(`data:${mime};base64,${data}`)},`;
});
writeFileSync(new URL('../components/chaintrace/chain-logos.ts', import.meta.url),
  `// Generated by scripts/embed-chain-logos.mjs; edit the source assets instead.\nexport const chainLogos = {\n${entries.join('\n')}\n} as const;\n`);
